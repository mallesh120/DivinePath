export const getAllWeeklyShlokas = () => Object.values(shlokaMastery);

export const getWeeklyShloka = (overrideId = null) => {
  if (overrideId && shlokaMastery[overrideId]) {
    return shlokaMastery[overrideId];
  }
  const all = Object.values(shlokaMastery);
  const now = new Date();
  const startOfYear = new Date(now.getFullYear(), 0, 1);
  const weekOfYear = Math.floor(((now - startOfYear) / (1000 * 60 * 60 * 24) + startOfYear.getDay()) / 7);
  return all[weekOfYear % all.length];
};
